
-- Tabela de serviços
CREATE TABLE tb_services (

 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
name VARCHAR(255) NOT NULL,
suggested_price DECIMAL(10,2) NOT NULL CHECK (suggested_price >= 0),
 active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Tabela de atendimentos
CREATE TABLE tb_attendances (

id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
service_name_snapshot   VARCHAR(255) NOT NULL,
amount_paid NUMERIC(19,2) NOT NULL DEFAULT 0.00,
 valid BOOLEAN NOT NULL DEFAULT TRUE,
date_time TIMESTAMP(0) NOT NULL,

provided_service_id     BIGINT NOT NULL,

CONSTRAINT fk_attendance_service
FOREIGN KEY (provided_service_id) REFERENCES tb_services(id)
);

-- Índice usado pelo @Index da entidade
CREATE INDEX idx_attendance_date ON tb_attendances (date_time);